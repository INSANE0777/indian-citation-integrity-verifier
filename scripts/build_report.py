#!/usr/bin/env python3
"""Generate report tables from saved experiments, then compile IEEE LaTeX."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_json(path):
    return json.loads((ROOT / path).read_text(encoding='utf8'))


def tex(value):
    substitutions = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '_': r'\_', '#': r'\#', '$': r'\$', '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}
    return ''.join(substitutions.get(c, c) for c in str(value))


def measurements():
    run = read_json('results/run_manifest.json')
    acquisition = read_json('data/manifest.json')
    baselines = read_json('results/evaluation.json')['evaluation']['baselines']
    retrieval = read_json('results/retrieval.json')
    hardware = read_json('results/hardware.json')
    dense = retrieval['dense']
    if dense['status'] != 'ok':
        raise ValueError('GPU experiment must have succeeded for this report')
    for path, expected in run['code_sha256'].items():
        if hashlib.sha256((ROOT / path.replace('\\', '/')).read_bytes()).hexdigest() != expected:
            raise ValueError(f'Code changed after experiments: {path}; rerun experiments')
    if hashlib.sha256((ROOT / 'data/corpus.jsonl').read_bytes()).hexdigest() != run['corpus_sha256']:
        raise ValueError('Corpus changed after experiments; rerun experiments')
    values = {
        'CorpusCount': f"{run['corpus_rows']:,}", 'ParagraphCount': f"{run['paragraphs']:,}",
        'RequestedCount': f"{acquisition['requested']:,} ({acquisition['selected_count']:,} selected keys)",
        'DevJudgments': run['dev_judgments'], 'TestJudgments': run['test_judgments'],
        'TestCount': f"{run['evaluation_cases']:,}", 'CpuName': hardware['cpu'],
        'RamSize': f"{hardware['ram_gib']:.2f} GiB", 'PythonVersion': run['python'],
        'TorchVersion': run['packages']['torch'],
        'FullFone': f"{baselines['full_verifier']['metrics']['grouped']['attention']['f1']:.3f}",
        'ExistFone': f"{baselines['citation_existence']['metrics']['grouped']['attention']['f1']:.3f}",
    }
    lines = ['% Generated by scripts/build_report.py from the recorded experiment.']
    lines += [rf'\newcommand{{\{key}}}{{{tex(value)}}}' for key, value in values.items()]
    rows = []
    for name, label in [('citation_existence', 'Citation existence'), ('literal_quote', 'Literal quote'), ('normalized_quote', 'Normalized quote'), ('full_verifier', 'Full verifier')]:
        metrics = baselines[name]['metrics']['grouped']['attention']
        rows.append(label + ' & ' + ' & '.join(f'{metrics[k]:.3f}' for k in ('accuracy', 'precision', 'recall', 'f1')) + r'\\')
    lines.append(r'\newcommand{\ComparisonRows}{' + '\n'.join(rows) + '}')
    bm, de = retrieval['bm25']['summary'], dense['test']['summary']
    facts = [
        ('BM25 test R@1 / R@5', f"{bm['recall_at_1']:.3f} / {bm['recall_at_5']:.3f}"),
        ('BM25 test MRR', f"{bm['mrr']:.3f}"),
        ('MiniLM test R@1 / R@5', f"{de['recall_at_1']:.3f} / {de['recall_at_5']:.3f}"),
        ('MiniLM test MRR', f"{de['mrr']:.3f}"),
        ('Test retrieval queries', de['count']),
        ('Model revision prefix', dense['revision'][:12]),
        ('Token limit / dimensions', f"{dense['max_seq_length']} / {dense['embedding_dimension']}"),
        ('Selected inference batch', dense['batch_size']),
        ('Paragraph indexing time', f"{dense['indexing_seconds']:.2f} s"),
    ]
    lines.append(r'\newcommand{\RetrievalRows}{' + '\n'.join(tex(a) + ' & ' + tex(b) + r'\\' for a, b in facts) + '}')
    lines.append(r'\newcommand{\TuningRows}{' + '\n'.join(f"{t['k1']} & {t['b']} & {t['recall_at_1']:.4f} & {t['mrr']:.4f}" + r'\\' for t in retrieval['bm25_grid']) + '}')
    return '\n'.join(lines) + '\n'


def bibliography():
    references = read_json('docs/references.json')
    lines = [r'\begin{thebibliography}{20}']
    for r in references:
        tail = ', doi: ' + tex(r['doi']) if r.get('doi') else ''
        if r['id'] == 'dataset':
            tail += r'. [Online]. Available: \url{' + r['url'] + '}'
        lines.append(r'\bibitem{' + r['id'] + '} ' + tex(r['authors']) + ', ``' + tex(r['title']) + r",'' \emph{" + tex(r['venue']) + '}, ' + str(r['year']) + tail + '.')
    return '\n'.join(lines + [r'\end{thebibliography}']) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--tectonic', help='Path to installed Tectonic compiler')
    parser.add_argument('--tables-only', action='store_true')
    args = parser.parse_args()
    report = ROOT / 'report'
    (report / 'measurements.tex').write_text(measurements(), encoding='utf8')
    (report / 'bibliography.tex').write_text(bibliography(), encoding='utf8')
    if args.tables_only:
        return
    compiler = args.tectonic or shutil.which('tectonic')
    local = ROOT / '.cache/tectonic-0.17.0/tectonic.exe'
    if not compiler and local.exists():
        compiler = str(local)
    if not compiler:
        raise SystemExit('Install Tectonic or pass --tectonic; tables generated successfully.')
    subprocess.run([compiler, str(report / 'main.tex'), '--outdir', str(report), '--keep-logs'], check=True, cwd=ROOT)
    log = (report / 'main.log').read_text(encoding='utf8', errors='replace')
    if 'Overfull' in log or 'undefined references' in log:
        raise SystemExit('PDF compiled but has layout/reference errors; inspect report/main.log')
    import pymupdf
    with pymupdf.open(report / 'main.pdf') as pdf:
        if not 6 <= len(pdf) <= 7:
            raise SystemExit(f'Report is {len(pdf)} pages; expected 6-7')
        text = ''.join(p.get_text() for p in pdf)
        if '�' in text:
            raise SystemExit('PDF contains replacement glyphs')
        print(f'Verified {len(pdf)}-page IEEE report')
    shutil.copyfile(report / 'main.pdf', report / 'Final_Report.pdf')
    (report / 'main.pdf').unlink()


if __name__ == '__main__':
    main()
